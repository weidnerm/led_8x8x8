def xyz_to_index(x, y, z):
    """Match led_cube.serial_xyz_to_rgb_index."""
    x = int(round(x))
    y = int(round(y))
    z = int(round(z))
    if x < 0 or x > 7 or y < 0 or y > 7 or z < 0 or z > 7:
        return None
    index = y * 64 + x * 8
    if (x & 1) == 0:
        index += 7 - z
    else:
        index += z
    return index


def _project_column(col, z, pos):
    """flash_16 four-face wrap. Returns in-bounds (x,y,z) tuples."""
    pts = []
    y = col + 7 - pos
    if 0 <= y <= 7:
        pts.append((0, y, z))
    x = pos - 7 - col
    if 0 <= x <= 7:
        pts.append((x, 0, z))
    y = pos - 14 - col
    if 0 <= y <= 7:
        pts.append((7, y, z))
    x = col + 28 - pos
    if 0 <= x <= 7:
        pts.append((x, 7, z))
    return pts


def normalize_text(text):
    if text is None:
        text = ''
    text = text.replace('\r', ' ').replace('\n', ' ')
    text = text.replace('<3', '♥')
    if len(text) > MAX_TEXT_LEN:
        text = text[:MAX_TEXT_LEN]
    return text


def text_to_columns(text):
    """List of 8-tall columns (1 = on). One blank column of gap after each glyph."""
    text = normalize_text(text)
    if not text:
        text = ' '
    columns = []
    columns.append([0] * 8)
    for ch in text:
        glyph = _FONT.get(ch) or _FONT.get(ch.upper()) or _FONT[' ']
        for c in range(5):
            col = [0] * 8
            bit = 0x10 >> c
            for r in range(7):
                if glyph[r] & bit:
                    col[r] = 1
            columns.append(col)
        columns.append([0] * 8)
    return columns


def frame_indices(columns, pos):
    lit = []
    seen = set()
    for col_i, col in enumerate(columns):
        for z, on in enumerate(col):
            if not on:
                continue
            for x, y, zz in _project_column(col_i, z, pos):
                idx = xyz_to_index(x, y, zz)
                if idx is not None and idx not in seen:
                    seen.add(idx)
                    lit.append(idx)
    lit.sort()
    return lit


def build_seq_lines(text, delay_ms=FRAME_DELAY_MS):
    columns = text_to_columns(text)
    lines = [
        'setup channel_1_count=512',
        'brightness 1,32',
        'delay %d' % delay_ms,
    ]
    nframes = len(columns) + 28
    for pos in range(nframes):
        lit = frame_indices(columns, pos)
        parts = ['fill 1']
        for idx in lit:
            parts.append('fill 1,0000ff,%d,1' % idx)
        parts.append('render')
        lines.append('; '.join(parts))
        lines.append('delay %d' % delay_ms)
    lines.append('fill 1; render')
    lines.append('delay 500')
    return lines


def write_seq_file(text, dest_path):
    lines = build_seq_lines(text)
    tmp = dest_path + '.tmp'
    with open(tmp, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    os.replace(tmp, dest_path)
    return dest_path, len(lines)
